"""The Automotive department, slice 2: fluids and electrics (gen#970).

Slice 1 (``tests/test_retail_automotive_970.py``) added the department and nine car care types.
Slice 2 adds six types (``automotive_fluids_rows``, ``docs/retail-automotive.md``): motor oil and
coolant under ``Automotive > Fluids``, and jump starters, tire inflators, phone mounts and car
chargers under ``Automotive > Electrics``. These checks hold the slice's Done-when: the ceiling
build holds at least 1,250 Automotive SKUs, each new type sits under its own family, no product id
or SKU id repeats, the new types' documents are the same bytes on every build, and a golden slice
(the first style of each new type) is pinned to
``tests/data/retail_automotive_fluids_970_golden.json``.

The fixture is regenerated by hand, never by the test: an edit to the rows that moves it is a
change a reviewer should see in the diff.
"""

from __future__ import annotations

import collections
import json
from pathlib import Path

import pytest

from retail_ceiling import ceiling_build
from synthetic_ecommerce_data.domains.retail import scale

ROOT = "Automotive"
#: The slice's Done-when floor (the issue's whole target is 1,900, over three slices).
SLICE_2_FLOOR = 1250
GOLDEN = Path(__file__).parent / "data" / "retail_automotive_fluids_970_golden.json"
#: The fields of a template document the golden slice pins.
PINNED = ("product_id", "title", "brand", "product_type", "category_path", "price", "sku_count")
#: The six types of slice 2, by their product_type, and the family each sits under.
FAMILY = {
    "Motor Oil": "Fluids",
    "Coolant": "Fluids",
    "Jump Starter": "Electrics",
    "Tire Inflator": "Electrics",
    "Phone Mount": "Electrics",
    "Car Charger": "Electrics",
}


@pytest.fixture(scope="module")
def ceiling() -> scale.Scaled:
    return ceiling_build()


def _automotive(records: list[dict]) -> list[dict]:
    return [d for d in records if d["category_path"][0] == ROOT]


def _slice_2(records: list[dict]) -> list[dict]:
    return [d for d in _automotive(records) if d["product_type"] in FAMILY]


def _golden_of(docs: list[dict]) -> list[dict]:
    """The first template of each product type, in build order, with its pinned fields and SKUs."""
    seen: dict[str, dict] = {}
    for doc in docs:
        if doc["product_type"] in seen:
            continue
        pinned = {k: doc[k] for k in PINNED}
        pinned["category_path"] = list(doc["category_path"])
        pinned["skus"] = [dict(s) for s in doc["skus"]]
        seen[doc["product_type"]] = pinned
    return [seen[t] for t in sorted(seen)]


def test_the_ceiling_build_holds_at_least_1250_automotive_skus(ceiling: scale.Scaled) -> None:
    skus = sum(d["sku_count"] for d in _automotive(ceiling.records))
    assert skus >= SLICE_2_FLOOR, f"{skus} Automotive SKUs in the ceiling build"


def test_every_new_type_is_under_its_automotive_family(ceiling: scale.Scaled) -> None:
    by_type = collections.defaultdict(set)
    for doc in _slice_2(ceiling.records):
        by_type[doc["product_type"]].add(tuple(doc["category_path"][:2]))
    assert set(by_type) == set(FAMILY), sorted(set(FAMILY) - set(by_type))
    elsewhere = {t: p for t, p in by_type.items() if p != {(ROOT, FAMILY[t])}}
    assert elsewhere == {}


def test_no_new_product_id_or_sku_id_repeats(ceiling: scale.Scaled) -> None:
    docs = _slice_2(ceiling.records)
    assert docs
    ids = collections.Counter(d["product_id"] for d in docs)
    skus = collections.Counter(s["sku"] for d in docs for s in d["skus"])
    assert {k: n for k, n in ids.items() if n > 1} == {}
    assert {k: n for k, n in skus.items() if n > 1} == {}
    everywhere = collections.Counter(d["product_id"] for d in ceiling.records)
    assert {d["product_id"] for d in docs if everywhere[d["product_id"]] > 1} == set()
    titles = collections.Counter(d["title"] for d in docs)
    assert {t: n for t, n in titles.items() if n > 1} == {}


def test_the_new_templates_are_byte_deterministic() -> None:
    first = json.dumps(_slice_2(scale.templates()), sort_keys=True, default=str)
    second = json.dumps(_slice_2(scale.templates()), sort_keys=True, default=str)
    assert _slice_2(json.loads(first)), "no slice 2 Automotive template"
    assert first == second


def test_the_golden_slice_matches_the_fixture() -> None:
    expected = json.loads(GOLDEN.read_text(encoding="utf-8"))
    got = json.loads(json.dumps(_golden_of(_slice_2(scale.templates())), default=str))
    assert {d["product_type"] for d in got} == set(FAMILY)
    assert got == expected
