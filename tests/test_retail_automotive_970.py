"""The Automotive department, slice 1: car care (gen#970).

The retail catalogue had no ``Automotive`` top level: ``core/departments.RETAIL`` did not list it
and no ``category_path`` started with it. Slice 1 adds the department and nine car care types
under ``Automotive > Car Care`` (``automotive_rows``, ``docs/retail-automotive.md``). These checks
hold the slice's Done-when: the ceiling build holds at least 600 Automotive SKUs, with no product
id or SKU id twice, the department's documents are the same bytes on every build, and a golden
slice (the first style of each type) is pinned to ``tests/data/retail_automotive_970_golden.json``.

The fixture is regenerated by hand, never by the test: an edit to the rows that moves it is a
change a reviewer should see in the diff.
"""

from __future__ import annotations

import collections
import json
from pathlib import Path

import pytest

from retail_ceiling import ceiling_build
from synthetic_ecommerce_data.core import departments
from synthetic_ecommerce_data.domains.retail import scale

ROOT = "Automotive"
#: The slice's Done-when floor (the issue's whole target is 1,900, over three slices).
SLICE_1_FLOOR = 600
GOLDEN = Path(__file__).parent / "data" / "retail_automotive_970_golden.json"
#: The fields of a template document the golden slice pins.
PINNED = ("product_id", "title", "brand", "product_type", "category_path", "price", "sku_count")
#: The nine car care types of slice 1, by their product_type.
CAR_CARE_TYPES = {
    "Car Shampoo",
    "Car Wax",
    "Car Polish",
    "Windshield Washer Fluid",
    "Car Interior Cleaner",
    "Wiper Blade",
    "Car Air Freshener",
    "Wash Mitt",
    "Microfiber Towel",
}


@pytest.fixture(scope="module")
def ceiling() -> scale.Scaled:
    return ceiling_build()


def _automotive(records: list[dict]) -> list[dict]:
    return [d for d in records if d["category_path"][0] == ROOT]


def _golden_of(docs: list[dict]) -> list[dict]:
    """The first template of each product type, in build order, with its pinned fields and SKUs."""
    seen: dict[str, dict] = {}
    for doc in docs:
        if doc["product_type"] in seen:
            continue
        pinned = {k: doc[k] for k in PINNED}
        pinned["category_path"] = list(doc["category_path"])
        pinned["skus"] = [dict(s) for s in doc["skus"]]
        seen[doc["product_type"]] = pinned
    return [seen[t] for t in sorted(seen)]


def test_automotive_is_a_retail_department() -> None:
    assert ROOT in departments.RETAIL


def test_the_ceiling_build_holds_at_least_600_automotive_skus(ceiling: scale.Scaled) -> None:
    skus = sum(d["sku_count"] for d in _automotive(ceiling.records))
    assert skus >= SLICE_1_FLOOR, f"{skus} Automotive SKUs in the ceiling build"


def test_every_car_care_type_is_under_automotive_car_care(ceiling: scale.Scaled) -> None:
    by_type = collections.defaultdict(set)
    for doc in _automotive(ceiling.records):
        by_type[doc["product_type"]].add(tuple(doc["category_path"][:2]))
    assert set(by_type) >= CAR_CARE_TYPES, sorted(CAR_CARE_TYPES - set(by_type))
    home = {(ROOT, "Car Care")}
    elsewhere = {t: p for t, p in by_type.items() if t in CAR_CARE_TYPES and p != home}
    assert elsewhere == {}


def test_no_automotive_product_id_or_sku_id_repeats(ceiling: scale.Scaled) -> None:
    docs = _automotive(ceiling.records)
    assert docs
    ids = collections.Counter(d["product_id"] for d in docs)
    skus = collections.Counter(s["sku"] for d in docs for s in d["skus"])
    assert {k: n for k, n in ids.items() if n > 1} == {}
    assert {k: n for k, n in skus.items() if n > 1} == {}
    everywhere = collections.Counter(d["product_id"] for d in ceiling.records)
    assert {d["product_id"] for d in docs if everywhere[d["product_id"]] > 1} == set()


def test_the_automotive_templates_are_byte_deterministic() -> None:
    first = json.dumps(_automotive(scale.templates()), sort_keys=True, default=str)
    second = json.dumps(_automotive(scale.templates()), sort_keys=True, default=str)
    assert _automotive(json.loads(first)), "no Automotive template"
    assert first == second


def test_the_golden_slice_matches_the_fixture() -> None:
    expected = json.loads(GOLDEN.read_text(encoding="utf-8"))
    got = json.loads(json.dumps(_golden_of(_automotive(scale.templates())), default=str))
    assert {d["product_type"] for d in got} >= CAR_CARE_TYPES
    assert got == expected
