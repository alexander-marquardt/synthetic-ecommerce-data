"""The Automotive department, slice 3: interior, and two types moved from Home (gen#970).

Slices 1 and 2 (``tests/test_retail_automotive_970.py``,
``tests/test_retail_automotive_fluids_970.py``) added the department, car care, fluids and
electrics. Slice 3 adds five types under ``Automotive > Interior`` (``automotive_interior_rows``,
``docs/retail-automotive.md``): seat covers, floor mats, trunk liners, steering wheel covers and
sun shades. It also moves Jump Leads to ``Automotive > Electrics`` and Car Boot Organiser to
``Automotive > Interior``, out of ``Home``.

These checks hold the issue's Done-when: the ceiling build holds at least 1,900 Automotive SKUs,
each new type sits under ``Automotive > Interior``, the moved types sit under ``Automotive`` and no
longer under ``Home``, no product id or SKU id repeats, the new types' documents are the same bytes
on every build, the color-bearing types offer the six main colors, every new type carries its
text-match decoys, and a golden slice (the first style of each new type) is pinned to
``tests/data/retail_automotive_interior_970_golden.json``.

The fixture is regenerated by hand, never by the test: an edit to the rows that moves it is a
change a reviewer should see in the diff.
"""

from __future__ import annotations

import collections
import json
from pathlib import Path

import pytest

from retail_ceiling import ceiling_build
from synthetic_ecommerce_data.domains.retail import scale, type_registry

ROOT = "Automotive"
#: The issue's Done-when: 95% of the 2,000-SKU target.
FLOOR = 1900
GOLDEN = Path(__file__).parent / "data" / "retail_automotive_interior_970_golden.json"
#: The fields of a template document the golden slice pins.
PINNED = ("product_id", "title", "brand", "product_type", "category_path", "price", "sku_count")
#: The five types of slice 3, by their product_type, and their spec keys.
INTERIOR = {
    "Seat Cover": "seat_cover",
    "Floor Mat": "floor_mat",
    "Trunk Liner": "trunk_liner",
    "Steering Wheel Cover": "steering_wheel_cover",
    "Sun Shade": "sun_shade",
}
#: The two types slice 3 moves out of Home, and the family each now sits under.
MOVED = {"Jump Leads": "Electrics", "Car Boot Organiser": "Interior"}
#: The six main colors (gen#275) every color-bearing type offers somewhere across its styles.
MAIN = {"Red", "Blue", "Green", "Yellow", "Black", "White"}
#: A sun shade is colorless: its reflective face is what it is, so no shopper picks it by color.
COLOR_BEARING = set(INTERIOR) - {"Sun Shade"}


@pytest.fixture(scope="module")
def ceiling() -> scale.Scaled:
    return ceiling_build()


def _automotive(records: list[dict]) -> list[dict]:
    return [d for d in records if d["category_path"][0] == ROOT]


def _slice_3(records: list[dict]) -> list[dict]:
    return [d for d in _automotive(records) if d["product_type"] in INTERIOR]


def _golden_of(docs: list[dict]) -> list[dict]:
    """The first template of each product type, in build order, with its pinned fields and SKUs."""
    seen: dict[str, dict] = {}
    for doc in docs:
        if doc["product_type"] in seen:
            continue
        pinned = {k: doc[k] for k in PINNED}
        pinned["category_path"] = list(doc["category_path"])
        pinned["skus"] = [dict(s) for s in doc["skus"]]
        seen[doc["product_type"]] = pinned
    return [seen[t] for t in sorted(seen)]


def test_the_ceiling_build_holds_at_least_1900_automotive_skus(ceiling: scale.Scaled) -> None:
    skus = sum(d["sku_count"] for d in _automotive(ceiling.records))
    assert skus >= FLOOR, f"{skus} Automotive SKUs in the ceiling build"


def test_every_new_type_is_under_automotive_interior(ceiling: scale.Scaled) -> None:
    by_type = collections.defaultdict(set)
    for doc in _slice_3(ceiling.records):
        by_type[doc["product_type"]].add(tuple(doc["category_path"][:2]))
    assert set(by_type) == set(INTERIOR), sorted(set(INTERIOR) - set(by_type))
    assert {t: p for t, p in by_type.items() if p != {(ROOT, "Interior")}} == {}


def test_jump_leads_and_car_boot_organiser_moved_from_home_to_automotive(
    ceiling: scale.Scaled,
) -> None:
    paths = collections.defaultdict(set)
    for doc in ceiling.records:
        if doc["product_type"] in MOVED:
            paths[doc["product_type"]].add(tuple(doc["category_path"][:2]))
    assert set(paths) == set(MOVED)
    assert {t: p for t, p in paths.items() if p != {(ROOT, MOVED[t])}} == {}
    specs = type_registry.specs().values()
    departments = {s.product_type: s.department for s in specs if s.product_type in MOVED}
    assert departments == dict.fromkeys(MOVED, ROOT)


def test_no_new_product_id_or_sku_id_repeats(ceiling: scale.Scaled) -> None:
    docs = _slice_3(ceiling.records)
    assert docs
    ids = collections.Counter(d["product_id"] for d in docs)
    skus = collections.Counter(s["sku"] for d in docs for s in d["skus"])
    assert {k: n for k, n in ids.items() if n > 1} == {}
    assert {k: n for k, n in skus.items() if n > 1} == {}
    everywhere = collections.Counter(d["product_id"] for d in ceiling.records)
    assert {d["product_id"] for d in docs if everywhere[d["product_id"]] > 1} == set()
    titles = collections.Counter(d["title"] for d in docs)
    assert {t: n for t, n in titles.items() if n > 1} == {}


def test_each_color_bearing_type_offers_the_six_main_colors() -> None:
    colors = collections.defaultdict(set)
    for doc in _slice_3(scale.templates()):
        colors[doc["product_type"]].update(s.get("color") for s in doc["skus"])
    missing = {t: sorted(MAIN - colors[t]) for t in COLOR_BEARING if not colors[t] >= MAIN}
    assert missing == {}
    assert colors["Sun Shade"] == {None}


def test_every_new_type_carries_two_text_match_decoys() -> None:
    specs = type_registry.specs()
    counts = {key: len(specs[key].decoys) if key in specs else 0 for key in INTERIOR.values()}
    assert {k: n for k, n in counts.items() if n < 2} == {}


def test_the_new_templates_are_byte_deterministic() -> None:
    first = json.dumps(_slice_3(scale.templates()), sort_keys=True, default=str)
    second = json.dumps(_slice_3(scale.templates()), sort_keys=True, default=str)
    assert _slice_3(json.loads(first)), "no slice 3 Automotive template"
    assert first == second


def test_the_golden_slice_matches_the_fixture() -> None:
    got = json.loads(json.dumps(_golden_of(_slice_3(scale.templates())), default=str))
    assert {d["product_type"] for d in got} == set(INTERIOR)
    assert GOLDEN.is_file(), f"no fixture at {GOLDEN.name}"
    expected = json.loads(GOLDEN.read_text(encoding="utf-8"))
    assert got == expected
