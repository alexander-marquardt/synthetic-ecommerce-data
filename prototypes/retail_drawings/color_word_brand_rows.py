#: The one type these rows introduce: it is registered through its spec file (gen#351), which
#: takes its rows from here, so :func:`docs` leaves them out (the spec's documents carry them).
SPEC_TYPES = frozenset({"Sugar"})


def spec_rows(product_type: str) -> tuple[CRow, ...]:
    """The rows of one spec-registered type, for its ``type_specs`` file."""
    return tuple(r for r in ROWS if r.product_type == product_type)


def docs() -> list[dict]:
    """Every row's catalog document, but the rows of a spec-registered type."""
    return [r.doc() for r in ROWS if r.product_type not in SPEC_TYPES]


def product_ids() -> frozenset[str]:
    """The product ids the module adds, for :func:`scale.derivable` to leave out."""
    return frozenset(f"BRD-{r.code}" for r in ROWS)


def table() -> str:
    """The docs table: one line per row, with its color word, true color and fix."""
    lines = [
        "| Product | Color word (field) | True color | Query fixed by |",
        "|---|---|---|---|",
    ]
    for b in BUCKETS:
        for r in (r for r in ROWS if r.bucket == b):
            lines.append(
                f"| {r.title} ({b}) | {r.color_word} ({r.named_in}) | {r.true_color} | {r.fix} |"
            )
    return "\n".join(lines)


def write_docs(path: str) -> None:
    """Rewrite the table between the markers of ``path`` (the docs page) from :data:`ROWS`."""
    from pathlib import Path

    p = Path(path)
    text = p.read_text()
    head, rest = text.split(DOCS_BEGIN, 1)
    tail = rest.split(DOCS_END, 1)[1]
    p.write_text(f"{head}{DOCS_BEGIN}\n{table()}\n{DOCS_END}{tail}")


