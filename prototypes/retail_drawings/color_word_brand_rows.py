"""Color-word brands and color-named lines beyond clothing (gen#312, decoy class 7).

Text search ranks a product first because its brand or product-line name holds a color word
that does not describe the product: a "Green Harrow" tin of yellow sweetcorn, a "Yellow
Skerry" red wine, a "Black Larch" orange drill, a "Silver Sedge" white sugar, a "Blue Heddon"
bag of brown almonds, a "Red Linnet" green cushion, and a spirit sold as "Red Cask", "Black
Cask" and "Blue Cask" that is the same amber. Every structured attribute stays true: the SKU
color, the wine style and the packaging color are what the product is.

All six brands are INVENTED (:data:`BRANDS`); the generator test checks each name against a
list of well-known brands. Each draws its own logo (:mod:`color_word_brand_styles`). The
rows are templates only: :func:`scale.derivable` leaves them out, as it does the other
failure-class rows. Each row says what fixes its query: ``generic`` (a color or brand
policy reads the brand or the color field) or ``special: <policy>``.

:func:`table` renders the docs table, ``docs/retail-color-word-brands.md`` carries it between
two markers, and a test holds the file equal to :func:`table`.
"""

